"""Composite datapath: a chain of existing stream designs connected by valid/ready FIFOs.

First instance: `fir_chain` -- two cascaded FIR filters (e.g. a cheap anti-alias stage followed by a sharp
shaping stage). The IR is a graph of stage IRs; the planner edits each stage's knobs (fold, dsp_regs, ...)
independently, and the emitter instantiates the stages' generated modules with a FIFO between them so a slow
(folded) second stage back-pressures the first.

Throughput of the chain = min over stages; DSP = sum; the critical path is whichever stage is slower, which the
planner sees because each stage keeps its own module name (stage0_*, stage1_*) in the reports.
"""

from __future__ import annotations

import hashlib
import json
import math
import re
from dataclasses import dataclass, field

from . import fir
from .fir import FirArch


@dataclass(frozen=True)
class FirChainArch:
    stages: tuple[FirArch, ...] = field(default_factory=lambda: (FirArch(taps=8, cutoff=0.4), FirArch(taps=32, cutoff=0.2)))
    fifo_depth: int = 16
    # the chain's data width is stage 0's; stage i>0 takes stage i-1's output truncated/rounded to its data_width
    round_mode: str = "truncate"   # truncate | round  (how the inter-stage width reduction is done)

    @property
    def data_width(self) -> int:
        return self.stages[0].data_width

    @property
    def acc_width(self) -> int:
        return self.stages[-1].acc_width

    def validate(self) -> list[str]:
        errs = []
        if not 2 <= len(self.stages) <= 4:
            errs.append("a chain has 2..4 stages")
        for i, st in enumerate(self.stages):
            errs += [f"stage {i}: {e}" for e in st.validate()]
        if self.fifo_depth not in (4, 8, 16, 32, 64):
            errs.append("fifo_depth must be 4, 8, 16, 32 or 64")
        if self.round_mode not in ("truncate", "round"):
            errs.append("round_mode must be truncate or round")
        return errs

    def to_dict(self) -> dict:
        return {"stages": [s.to_dict() for s in self.stages], "fifo_depth": self.fifo_depth, "round_mode": self.round_mode}

    @classmethod
    def from_dict(cls, d: dict) -> "FirChainArch":
        stages = tuple(FirArch.from_dict(s) for s in d.get("stages", [])) or cls().stages
        return cls(stages=stages, fifo_depth=int(d.get("fifo_depth", 16)), round_mode=d.get("round_mode", "truncate"))

    def digest(self, backend: str = "ecp5") -> str:
        d = self.to_dict()
        for s in d["stages"]:
            s.pop("cutoff", None)
            if backend != "xc7s50":
                s.pop("acc_in_dsp", None)
        return hashlib.sha256(json.dumps(d, sort_keys=True).encode()).hexdigest()[:12]


def throughput(a: FirChainArch) -> float:
    return round(min(fir.throughput(s) for s in a.stages), 4)


def latency_cycles(a: FirChainArch) -> int:
    return sum(fir.latency_cycles(s) for s in a.stages) + 2 * (len(a.stages) - 1)


def _rename(text: str, prefix: str) -> str:
    """Give a stage's generated modules unique names (fir_top -> <prefix>_fir_top, fir_mult -> <prefix>_fir_mult)."""
    return re.sub(r"\b(fir_top|fir_mult)\b", lambda m: f"{prefix}_{m.group(1)}", text)


def emit_fir_chain(a: FirChainArch, backend: str = "ecp5") -> str:
    parts = [f"// Generated by silicon-agent -- do not edit. IR: {a.to_dict()}\n", "typedef logic signed [63:0] sd;\n"]
    for i, st in enumerate(a.stages):
        body = fir.emit_fir(st, backend=backend)
        body = body.split("\n", 1)[1]  # drop the stage's own header comment
        body = body.replace("`default_nettype none\n", "").replace("`default_nettype wire\n", "").replace("typedef logic signed [63:0] sd;\n", "")
        parts.append(_rename(body, f"s{i}"))
    n = len(a.stages)
    DW0, AWn = a.stages[0].data_width, a.stages[-1].acc_width
    inst = []
    for i, st in enumerate(a.stages):
        src = "in_data" if i == 0 else f"q{i}_data"
        src_v = "in_valid" if i == 0 else f"q{i}_valid"
        rdy = "in_ready" if i == 0 else f"q{i}_ready"
        ov, od = (f"s{i}_ov", f"s{i}_od")
        inst.append(f"""    logic {ov}; logic signed [{st.acc_width - 1}:0] {od};
    s{i}_fir_top u_s{i} (.clk(clk), .rst(rst), .in_valid({src_v}), .in_data({src}), .in_ready({rdy}), .out_valid({ov}), .out_data({od}));""")
        if i < n - 1:
            nxt = a.stages[i + 1]
            # width reduction: keep the top data_width bits of the accumulator (scaled by the coefficient gain) or round
            shift = st.acc_width - nxt.data_width
            # the reduction is computed on the full accumulator inside a combinational block that *reads every
            # bit* (adding the rounding constant or 0): a plain slice leaves the dropped bits as an unused partial
            # bus that synth_gowin keeps as a $buf cell nextpnr-himbaechel cannot place
            rc = f"{st.acc_width}'(1 << {shift - 1})" if (a.round_mode == "round" and shift > 0) else f"{st.acc_width}'(0)"
            inst.append(f"    logic signed [{st.acc_width - 1}:0] s{i}_full; always_comb s{i}_full = {od} + {rc};")
            red = f"s{i}_full[{st.acc_width - 1}:{shift}]" if shift > 0 else f"s{i}_full"
            inst.append(f"""    logic q{i + 1}_valid, q{i + 1}_ready; logic signed [{nxt.data_width - 1}:0] q{i + 1}_data;
    logic [$clog2(FIFO+1)-1:0] q{i + 1}_count;
    logic signed [{nxt.data_width - 1}:0] s{i}_red; assign s{i}_red = {nxt.data_width}'({red});
    sa_chain_fifo #(.W({nxt.data_width}), .D(FIFO)) u_q{i + 1} (.clk(clk), .rst(rst), .wr({ov}), .wdata(s{i}_red),
        .rd(q{i + 1}_valid & q{i + 1}_ready), .rdata(q{i + 1}_data), .valid(q{i + 1}_valid), .count(q{i + 1}_count));
    // the stage before a FIFO must not produce more than the FIFO can hold: stall it when nearly full
    assign s{i}_room = (q{i + 1}_count + 4 <= FIFO);""")
    # input ready: stage 0 ready AND room in q1 (stage 0 has fixed latency, so bound by FIFO headroom)
    rooms = " & ".join(f"s{i}_room" for i in range(n - 1)) or "1'b1"
    top = f"""
module fir_chain_top #(
    parameter int DW = {DW0},
    parameter int AW = {AWn},
    parameter int FIFO = {a.fifo_depth}
) (
    input  wire                   clk,
    input  wire                   rst,
    input  wire                   in_valid,
    input  wire signed [DW-1:0]   in_data,
    output logic                  in_ready,
    output logic                  out_valid,
    output logic signed [AW-1:0]  out_data
);
    logic s0_in_ready;
    {chr(10).join(f"    logic s{i}_room;" for i in range(n - 1))}
    wire gate = {rooms};
{chr(10).join(inst).replace("u_s0 (.clk(clk), .rst(rst), .in_valid(in_valid), .in_data(in_data), .in_ready(in_ready)", "u_s0 (.clk(clk), .rst(rst), .in_valid(in_valid & gate), .in_data(in_data), .in_ready(s0_in_ready)")}
    assign in_ready = s0_in_ready & gate;
    assign out_valid = s{n - 1}_ov;
    assign out_data  = s{n - 1}_od;
endmodule

module sa_chain_fifo #(parameter int W = 8, parameter int D = 16) (
    input wire clk, input wire rst, input wire wr, input wire [W-1:0] wdata,
    input wire rd, output logic [W-1:0] rdata, output logic valid, output logic [$clog2(D+1)-1:0] count);
    logic [W-1:0] mem [0:D-1]; logic [$clog2(D)-1:0] wp, rp;
    always_ff @(posedge clk) begin
        if (rst) begin wp <= '0; rp <= '0; count <= '0; end
        else begin
            if (wr) begin mem[wp] <= wdata; wp <= wp + 1'b1; end
            if (rd & valid) rp <= rp + 1'b1;
            count <= count + (wr ? 1 : 0) - ((rd & valid) ? 1 : 0);
        end
    end
    assign valid = count != 0;
    assign rdata = mem[rp];
endmodule
"""
    return "`default_nettype none\n" + "\n".join(parts) + top + "`default_nettype wire\n"
