"""Delivery: an AXI4-Stream wrapper around a generated core, and a zip that holds everything an engineer
needs to use the result -- RTL, wrapper, testbench + vectors, timing/resource reports, the trajectory, a README.

AXI-Stream mapping (one slave stream in, one master stream out, TDATA packed little-endian, TKEEP/TSTRB absent):
  matmul   s_axis: TDATA = {b_row, a_col}  (C*W + R*W bits, rounded to bytes), TLAST = in_last (end of a K-column)
           m_axis: TDATA = {out_row, c_row} (one result row per beat), TLAST on the last row of a tile.
           The core has no input back-pressure (it accepts one beat per cycle as long as K >= min_k_full_rate);
           the wrapper only asserts TREADY while its output FIFO can absorb a full tile, so no result is lost.
  fir      s_axis: TDATA = in_data (DW bits -> bytes); m_axis: TDATA = out_data (AW bits -> bytes). in_ready -> TREADY.
  conv2d   s_axis: TDATA = pixel, TUSER[0] = frame_start; m_axis: TDATA = out_data. in_ready -> TREADY.
Output back-pressure: the cores emit without a ready input, so the wrapper buffers outputs in a FIFO and lets
the input stall (TREADY low) when the FIFO is nearly full. The FIFO depth is the only wrapper knob.
"""

