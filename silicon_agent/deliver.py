"""Delivery: an AXI4-Stream wrapper around a generated core, and a zip that holds everything an engineer
needs to use the result -- RTL, wrapper, testbench + vectors, timing/resource reports, the trajectory, a README.

AXI-Stream mapping (one slave stream in, one master stream out, TDATA packed little-endian, TKEEP/TSTRB absent):
  matmul   s_axis: TDATA = {b_row, a_col}  (C*W + R*W bits, rounded to bytes), TLAST = in_last (end of a K-column)
           m_axis: TDATA = {out_row, c_row} (one result row per beat), TLAST on the last row of a tile.
           The core has no input back-pressure (it accepts one beat per cycle as long as K >= min_k_full_rate);
           the wrapper only asserts TREADY while its output FIFO can absorb a full tile, so no result is lost.
  fir      s_axis: TDATA = in_data (DW bits -> bytes); m_axis: TDATA = out_data (AW bits -> bytes). in_ready -> TREADY.
  conv2d   s_axis: TDATA = pixel, TUSER[0] = frame_start; m_axis: TDATA = out_data. in_ready -> TREADY.
Output back-pressure: the cores emit without a ready input, so the wrapper buffers outputs in a FIFO and lets
the input stall (TREADY low) when the FIFO is nearly full. The FIFO depth is the only wrapper knob.
"""

from __future__ import annotations

import io
import json
import math
import time
import zipfile
from pathlib import Path

from .designs import DESIGNS, Design


def _bytes(bits: int) -> int:
    return max(1, (bits + 7) // 8)


def axis_wrapper(d: Design, ir, fifo_depth: int = 64) -> str:
    """AXI4-Stream wrapper SystemVerilog for the design's core."""
    if d.kind == "matmul":
        R, C, W, AW = ir.pe_rows, ir.pe_cols, ir.data_width, ir.acc_width
        in_bits, out_bits = R * W + C * W, C * AW + max(1, math.ceil(math.log2(R + 1)))
        IB, OB = 8 * _bytes(in_bits), 8 * _bytes(out_bits)
        rowb = max(1, math.ceil(math.log2(R + 1)))
        return f"""// AXI4-Stream wrapper for matmul_top (generated by silicon-agent)
// s_axis TDATA = {{b_row[{C * W - 1}:0], a_col[{R * W - 1}:0]}}, TLAST = last k-column of a tile
// m_axis TDATA = {{out_row, c_row}}: one C-wide result row per beat, TLAST on row R-1
`default_nettype none
module matmul_axis #(parameter int FIFO = {fifo_depth}) (
    input  wire            aclk,
    input  wire            aresetn,
    input  wire            s_axis_tvalid,
    output logic           s_axis_tready,
    input  wire [{IB - 1}:0] s_axis_tdata,
    input  wire            s_axis_tlast,
    output logic           m_axis_tvalid,
    input  wire            m_axis_tready,
    output logic [{OB - 1}:0] m_axis_tdata,
    output logic           m_axis_tlast
);
    localparam int R = {R}, C = {C}, W = {W}, AW = {AW}, OBITS = {out_bits};
    logic rst; assign rst = ~aresetn;
    logic busy, out_valid; logic [{rowb - 1}:0] out_row; logic [C*AW-1:0] c_row;
    // one tile in flight produces R rows; admit a new tile only while the FIFO has room for it
    logic [$clog2(FIFO+1)-1:0] count;
    assign s_axis_tready = aresetn && (count + R*2 <= FIFO);
    wire accept = s_axis_tvalid & s_axis_tready;
    matmul_top core (.clk(aclk), .rst(rst), .in_valid(accept), .in_last(s_axis_tlast),
                     .a_col(s_axis_tdata[R*W-1:0]), .b_row(s_axis_tdata[R*W +: C*W]),
                     .busy(busy), .out_valid(out_valid), .out_row(out_row), .c_row(c_row));
    sa_fifo #(.W(OBITS + 1), .D(FIFO)) q (.clk(aclk), .rst(rst),
        .wr(out_valid), .wdata({{out_row == R-1, out_row, c_row}}),
        .rd(m_axis_tvalid & m_axis_tready), .rdata({{m_axis_tlast, m_axis_tdata[OBITS-1:0]}}), .valid(m_axis_tvalid), .count(count));
    {"assign m_axis_tdata[" + str(OB - 1) + ":OBITS] = '0;" if OB > out_bits else ""}
endmodule
{_fifo()}
`default_nettype wire
"""
    if d.kind == "fir":
        DW, AW = ir.data_width, ir.acc_width
        IB, OB = 8 * _bytes(DW), 8 * _bytes(AW)
        return f"""// AXI4-Stream wrapper for fir_top (generated by silicon-agent)
`default_nettype none
module fir_axis #(parameter int FIFO = {fifo_depth}) (
    input  wire            aclk,
    input  wire            aresetn,
    input  wire            s_axis_tvalid,
    output logic           s_axis_tready,
    input  wire [{IB - 1}:0] s_axis_tdata,
    output logic           m_axis_tvalid,
    input  wire            m_axis_tready,
    output logic [{OB - 1}:0] m_axis_tdata,
    output logic           m_axis_tlast
);
    localparam int DW = {DW}, AW = {AW};
    logic rst; assign rst = ~aresetn;
    logic in_ready, out_valid; logic signed [AW-1:0] out_data;
    logic [$clog2(FIFO+1)-1:0] count;
    wire room = (count + 8 <= FIFO);
    assign s_axis_tready = aresetn & in_ready & room;
    fir_top core (.clk(aclk), .rst(rst), .in_valid(s_axis_tvalid & room), .in_data(s_axis_tdata[DW-1:0]),
                  .in_ready(in_ready), .out_valid(out_valid), .out_data(out_data));
    sa_fifo #(.W(AW), .D(FIFO)) q (.clk(aclk), .rst(rst), .wr(out_valid), .wdata(out_data),
        .rd(m_axis_tvalid & m_axis_tready), .rdata(m_axis_tdata[AW-1:0]), .valid(m_axis_tvalid), .count(count));
    {"assign m_axis_tdata[" + str(OB - 1) + ":AW] = {" + str(OB - AW) + "{m_axis_tdata[AW-1]}};" if OB > AW else ""}
    assign m_axis_tlast = 1'b0;
endmodule
{_fifo()}
`default_nettype wire
"""
    if d.kind == "conv2d":
        DW, AW = ir.data_width, ir.acc_width
        IB, OB = 8 * _bytes(DW), 8 * _bytes(AW)
        return f"""// AXI4-Stream wrapper for conv2d_top (generated by silicon-agent)
// s_axis TUSER[0] = first pixel of a frame
`default_nettype none
module conv2d_axis #(parameter int FIFO = {fifo_depth}) (
    input  wire            aclk,
    input  wire            aresetn,
    input  wire            s_axis_tvalid,
    output logic           s_axis_tready,
    input  wire [{IB - 1}:0] s_axis_tdata,
    input  wire [0:0]      s_axis_tuser,
    output logic           m_axis_tvalid,
    input  wire            m_axis_tready,
    output logic [{OB - 1}:0] m_axis_tdata,
    output logic           m_axis_tlast
);
    localparam int DW = {DW}, AW = {AW};
    logic rst; assign rst = ~aresetn;
    logic in_ready, out_valid; logic signed [AW-1:0] out_data;
    logic [$clog2(FIFO+1)-1:0] count;
    wire room = (count + 8 <= FIFO);
    assign s_axis_tready = aresetn & in_ready & room;
    conv2d_top core (.clk(aclk), .rst(rst), .in_valid(s_axis_tvalid & room), .frame_start(s_axis_tuser[0]),
                     .in_data(s_axis_tdata[DW-1:0]), .in_ready(in_ready), .out_valid(out_valid), .out_data(out_data));
    sa_fifo #(.W(AW), .D(FIFO)) q (.clk(aclk), .rst(rst), .wr(out_valid), .wdata(out_data),
        .rd(m_axis_tvalid & m_axis_tready), .rdata(m_axis_tdata[AW-1:0]), .valid(m_axis_tvalid), .count(count));
    {"assign m_axis_tdata[" + str(OB - 1) + ":AW] = {" + str(OB - AW) + "{m_axis_tdata[AW-1]}};" if OB > AW else ""}
    assign m_axis_tlast = 1'b0;
endmodule
{_fifo()}
`default_nettype wire
"""
    raise ValueError(f"no AXI wrapper for design {d.kind}")


def _fifo() -> str:
    return """
module sa_fifo #(parameter int W = 8, parameter int D = 64) (
    input  wire clk, input wire rst,
    input  wire wr, input wire [W-1:0] wdata,
    input  wire rd, output logic [W-1:0] rdata, output logic valid,
    output logic [$clog2(D+1)-1:0] count
);
    logic [W-1:0] mem [0:D-1];
    logic [$clog2(D)-1:0] wp, rp;
    always_ff @(posedge clk) begin
        if (rst) begin wp <= '0; rp <= '0; count <= '0; end
        else begin
            if (wr) begin mem[wp] <= wdata; wp <= wp + 1'b1; end
            if (rd & valid) rp <= rp + 1'b1;
            count <= count + (wr ? 1 : 0) - ((rd & valid) ? 1 : 0);
        end
    end
    assign valid = count != 0;
    assign rdata = mem[rp];
endmodule"""


def readme(job: dict, best: dict, design: Design, unit: str, lang: str = "en") -> str:
    spec, m = job["spec"], best["metrics"]
    c = spec["constraints"]
    st = m.get("sim_stages") or {}
    ladder = "\n".join(f"  - {v.get('label', k)}: {'pass' if v.get('passed') else 'FAIL' if v.get('passed') is False else 'n/a'}" for k, v in st.items())
    cp = m.get("critical_path") or []
    cpt = f"{cp[0]['total_ns']} ns: " + " -> ".join(f"{e['kind']} {e['rtl']} ({e['logic_ns']}+{e['route_ns']})" for e in cp[1:6]) if len(cp) > 1 else "n/a"
    return f"""# {spec.get('task', design.kind)}

Generated by silicon-agent on {time.strftime('%Y-%m-%d')} from job `{job.get('id', '')}`.

## Result (real place-and-route on {spec['backend']})
- Fmax {m['fmax_mhz']:.1f} MHz (target >= {c['fmax_mhz']} MHz)
- {m['lut']} LUT, {m['ff']} FF, {m['dsp']} DSP, {m.get('bram', 0)} BRAM
- throughput {best['throughput']} {unit}, latency {best.get('latency_cycles', '?')} cycles
- behavioral simulation vs. Python golden model: {'pass' if m.get('sim_passed') else 'FAIL'}
{ladder}
- critical path: {cpt}

## Files
- `rtl/{design.top}.sv` -- the core. Streaming valid/ready interface, synchronous active-high reset.
- `rtl/{design.kind}_axis.sv` -- AXI4-Stream wrapper (`{design.kind}_axis`) with an output FIFO; see the header for the TDATA layout.
- `sim/tb.sv`, `sim/stim.hex`, `sim/exp.hex` -- self-checking vector testbench (prints `RESULT PASS`); run with any SystemVerilog simulator:
  `iverilog -g2012 -o tb sim/tb.sv rtl/{design.top}.sv && vvp tb`
- `reports/` -- synthesis/P&R logs and reports as produced by the tools
- `trajectory.json` -- every design the agent evaluated with its measured metrics
- `spec.json`, `ir.json` -- the task and the chosen architecture

## Architecture (IR)
```
{json.dumps({k: v for k, v in best['ir'].items() if k != 'coefs'}, indent=2)}
```
Locked task parameters: `{json.dumps(spec.get('locked', {}))}`.
"""


def package(job: dict, results_dir: Path, runs_dir: Path) -> bytes:
    """Zip bytes for a finished job's best design."""
    d = DESIGNS[job["spec"].get("design", "matmul")]
    best = (job.get("summary") or {}).get("best")
    if not best:
        raise ValueError("no feasible design")
    backend = job["spec"].get("backend", "ecp5")
    ir = d.ir_cls.from_dict(best["ir"])
    rtl = d.emit(ir, backend=backend)
    unit = (job.get("summary") or {}).get("throughput_unit", "")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(f"rtl/{d.top}.sv", rtl)
        try:
            z.writestr(f"rtl/{d.kind}_axis.sv", axis_wrapper(d, ir))
        except ValueError:
            pass
        if d.vectors and d.tb:
            stim, exp = d.vectors(ir)
            period = 1000.0 / job["spec"]["constraints"]["fmax_mhz"]
            z.writestr("sim/tb.sv", d.tb(ir, period))
            z.writestr("sim/stim.hex", "\n".join(stim) + "\n")
            z.writestr("sim/exp.hex", "\n".join(exp) + "\n")
        # reports from the run directory (hash of backend + RTL, as evaluate() names it)
        import hashlib
        h = hashlib.sha256(f"{backend}\n{rtl}".encode()).hexdigest()[:16]
        work = runs_dir / h
        for sub in ("pnr", "vivado"):
            for f in (work / sub).glob("*") if (work / sub).exists() else []:
                if f.is_file() and f.suffix in (".log", ".txt", ".json", ".rpt", ".ys", ".tcl", ".xdc") and f.stat().st_size < 2_000_000 and f.name not in ("synth.json", "core.json"):
                    z.write(f, f"reports/{sub}/{f.name}")
        hist = [{k: e[k] for k in ("iteration", "ir", "metrics", "violations", "throughput", "action") if k in e} for e in job["events"] if e["kind"] == "result"]
        z.writestr("trajectory.json", json.dumps(hist, indent=1))
        z.writestr("spec.json", json.dumps(job["spec"], indent=2))
        z.writestr("ir.json", json.dumps(ir.to_dict(), indent=2))
        z.writestr("README.md", readme(job, best, d, unit))
    return buf.getvalue()
