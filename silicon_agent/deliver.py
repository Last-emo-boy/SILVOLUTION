def oss_build_script(job: dict, d: Design, ir) -> str:
    be = job["spec"].get("backend", "ecp5")
    top = d.top
    flows = {
        "ecp5": f"yosys -p \"plugin -i slang; read_slang --top {top} rtl/{top}.sv; synth_ecp5 -top {top} -json build/{top}.json\" && nextpnr-ecp5 --45k --package CABGA381 --speed 6 --json build/{top}.json --lpf project/pins.lpf --textcfg build/{top}.config && ecppack build/{top}.config build/{top}.bit",
        "ice40": f"yosys -p \"plugin -i slang; read_slang --top {top} rtl/{top}.sv; synth_ice40 -dsp -top {top} -json build/{top}.json\" && nextpnr-ice40 --up5k --package sg48 --json build/{top}.json --pcf project/pins.pcf --asc build/{top}.asc && icepack build/{top}.asc build/{top}.bin",
        "gowin": f"yosys -p \"plugin -i slang; read_slang --top {top} rtl/{top}.sv; synth_gowin -top {top} -json build/{top}.json\" && nextpnr-himbaechel --device GW1NR-LV9QN88PC6/I5 --vopt family=GW1N-9C --vopt cst=project/pins.cst --json build/{top}.json --write build/{top}_pnr.json && gowin_pack -d GW1N-9C -o build/{top}.fs build/{top}_pnr.json",
    }
    cmd = flows.get(be, flows["ecp5"])
    return f"""#!/usr/bin/env bash
# silicon-agent: {spec_task(job)} -- open-source bitstream flow for {be}
# needs oss-cad-suite on PATH; write your board's pin constraints to project/pins.{{lpf,pcf,cst}} first
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p build
{cmd}
echo "bitstream in build/"
"""


def package(job: dict, results_dir: Path, runs_dir: Path) -> bytes:
    """Zip bytes for a finished job's best design."""
    d = DESIGNS[job["spec"].get("design", "matmul")]
    best = (job.get("summary") or {}).get("best")
    if not best:
        raise ValueError("no feasible design")
    backend = job["spec"].get("backend", "ecp5")
    ir = d.ir_cls.from_dict(best["ir"])
    rtl = d.emit(ir, backend=backend)
    unit = (job.get("summary") or {}).get("throughput_unit", "")
    import hashlib
    h = hashlib.sha256(f"{backend}\n{rtl}".encode()).hexdigest()[:16]
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(f"rtl/{d.top}.sv", rtl)
        try:
            wname = f"{d.top}_axis" if d.kind.startswith("rtl:") else f"{d.kind}_axis"
            z.writestr(f"rtl/{wname}.sv", axis_wrapper(d, ir))
        except ValueError:
            pass
        if d.vectors and d.tb:
            stim, exp = d.vectors(ir)
            period = 1000.0 / job["spec"]["constraints"]["fmax_mhz"]
            z.writestr("sim/tb.sv", d.tb(ir, period))
            z.writestr("sim/stim.hex", "\n".join(stim) + "\n")
            z.writestr("sim/exp.hex", "\n".join(exp) + "\n")
        elif d.tb:
            # BYO-RTL: the user's own self-checking bench
            z.writestr("sim/tb.sv", d.tb(ir, 1000.0 / job["spec"]["constraints"]["fmax_mhz"]))
        if backend == "sky130":
            # the ASIC deliverable: the routed netlist and the GDS of the best iteration, from the run's pnr/ directory
            for name in ("6_final.v", "6_final.gds", "6_finish.rpt", "6_report.json"):
                f = runs_dir / h / "pnr" / name
                if f.exists():
                    z.write(f, f"asic/{name}")
        # reports from the run directory (hash of backend + RTL, as evaluate() names it)

        work = runs_dir / h
        for sub in ("pnr", "vivado"):
            for f in (work / sub).glob("*") if (work / sub).exists() else []:
                if f.is_file() and f.suffix in (".log", ".txt", ".json", ".rpt", ".ys", ".tcl", ".xdc") and f.stat().st_size < 2_000_000 and f.name not in ("synth.json", "core.json"):
                    z.write(f, f"reports/{sub}/{f.name}")
        hist = [{k: e[k] for k in ("iteration", "ir", "metrics", "violations", "throughput", "action") if k in e} for e in job["events"] if e["kind"] == "result"]
        z.writestr("trajectory.json", json.dumps(hist, indent=1))
        z.writestr("project/create_vivado.tcl", vivado_project_tcl(job, d, ir))
        z.writestr("project/constraints.xdc", f"# {spec_task(job)}\ncreate_clock -period {1000.0 / job['spec']['constraints']['fmax_mhz']:.3f} -name clk [get_ports aclk]\n# add pin LOCs / IOSTANDARDs for your board here\n")
        z.writestr("project/build_oss.sh", oss_build_script(job, d, ir))
        z.writestr("spec.json", json.dumps(job["spec"], indent=2))
        frep = results_dir / "formal" / "report.json"
        if frep.exists():
            z.write(frep, "reports/formal.json")
        z.writestr("ir.json", json.dumps(ir.to_dict(), indent=2))
        sb = _studio_bundle(d)
        if sb:
            # the studio's evidence travels with the design: the spec, both models, every revision's check
            sdir = Path(sb.get("dir") or "")
            if (sdir / "SPEC.md").exists():
                z.write(sdir / "SPEC.md", "studio/SPEC.md")
            if sb.get("golden"):
                z.writestr("studio/golden.py", sb["golden"])
            if (sb.get("reference") or {}).get("code"):
                z.writestr("studio/reference.py", sb["reference"]["code"])
            z.writestr("studio/revisions.json", json.dumps([{k: v for k, v in r.items() if k != "files"} for r in sb.get("revisions") or []], indent=1))
        z.writestr("README.md", readme(job, best, d, unit))
    return buf.getvalue()
