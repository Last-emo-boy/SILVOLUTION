"""Mutation score of a design's verification: does the testbench catch injected bugs?

A generator change that comes with "the tests pass" is only as good as the tests. Mutating the generated RTL
(flip a comparison, drop a pipeline register's enable, off-by-one on a constant, swap an add for a subtract)
and re-running the behavioral testbench on each mutant measures how many such bugs it would notice. The score
(killed / total) is one of the gates a proposed change has to clear, and the surviving mutants say where the
testbench is blind.

Mutants are generated by regex on the SystemVerilog text, so they are syntactic and cheap; a mutant that does not
compile is dropped (not counted). Each mutant is one behavioral cocotb run (seconds for the small designs).
"""

from __future__ import annotations

import re
import tempfile
from pathlib import Path

from .designs import Design

# (name, pattern, replacement, max occurrences to mutate): each match becomes one mutant. Patterns target
# datapath statements (assignments), never declarations, port lists or loop headers -- mutating a width or a
# dead loop bound makes an equivalent mutant that teaches nothing.
OPERATORS: list[tuple[str, str, str, int]] = [
    ("add_to_sub", r"(<=|=)([^;<]*\w\s*)\+(\s*\w[^;]*;)", r"\1\2-\3", 4),
    ("sub_to_add", r"(<=|=)([^;<]*\w\s*)-(\s*\w[^;]*;)", r"\1\2+\3", 4),
    ("cond_lt_to_le", r"if \(([^()]*\w)\s*<\s*(\w[^()]*)\)", r"if (\1 <= \2)", 3),
    ("cond_eq_to_neq", r"if \(([^()]*)==([^()]*)\)", r"if (\1!=\2)", 3),
    ("sel_flip", r"\?\s*([^:;]+?)\s*:\s*([^;]+?);", r"? \2 : \1;", 3),
    ("shift_off_by_one", r">>>\s*(\d+)", lambda m: f">>> {int(m.group(1)) + 1}", 3),
    ("drop_enable", r"else if \((\w+)\) ", r"else if (1'b1) ", 3),
    ("stuck_enable", r"else if \((\w+)\) ", r"else if (1'b0) ", 2),
    ("invert_valid", r"out_valid\s*<=\s*(\w+);", r"out_valid <= ~\1;", 1),
    ("index_off_by_one", r"<= (\w+)\[(\w+)-1\];", r"<= \1[\2];", 3),
]

# lines the mutants must leave alone: declarations, ports, parameters, loop headers (their bounds are structure,
# not datapath), and the header comment that carries the IR
_SKIP = re.compile(r"^\s*(//|`|typedef|module|endmodule|input|output|parameter|localparam|logic|wire|reg|for\s*\(|generate|endgenerate|assign\s+\w+_ext|.*begin\s*:\s*g_)")


def mutants(rtl: str, limit: int = 24) -> list[tuple[str, str]]:
    """[(label, mutated rtl)] -- each differs from `rtl` in exactly one place."""
    out: list[tuple[str, str]] = []
    lines = rtl.split("\n")
    for name, pat, rep, cap in OPERATORS:
        done = 0
        for i, line in enumerate(lines):
            if done >= cap or _SKIP.match(line):
                continue
            m = re.search(pat, line)
            if not m:
                continue
            new_line = line[:m.start()] + (rep(m) if callable(rep) else m.expand(rep)) + line[m.end():]
            if new_line == line:
                continue
            out.append((f"{name}@{i + 1}", "\n".join(lines[:i] + [new_line] + lines[i + 1:])))
            done += 1
            if len(out) >= limit:
                return out
    return out


def score(d: Design, ir, rtl: str, work: Path | None = None, limit: int = 24) -> dict:
    """Run the behavioral testbench on every mutant. Returns killed/survived counts, the survivors (where the
    bench is blind) and the mutants that did not compile (not counted)."""
    from . import eda
    work = work or Path(tempfile.mkdtemp(prefix="sa_mut_"))
    res = {"total": 0, "killed": 0, "survived": [], "uncompilable": 0}
    for label, text in mutants(rtl, limit):
        w = work / re.sub(r"[^\w]", "_", label)
        (w / "rtl").mkdir(parents=True, exist_ok=True)
        (w / "rtl" / f"{d.top}.sv").write_text(text)
        # a mutant that stalls the stream hangs the bench: the short timeout counts it as killed
        ok, log, _ = eda.simulate(d, ir, w, timeout=240)
        if not ok and ("error:" in log.lower() or "CalledProcessError" in log) and "COCOTB_RESULT" not in log:
            res["uncompilable"] += 1
            continue
        res["total"] += 1
        if ok:
            res["survived"].append(label)
        else:
            res["killed"] += 1
    res["score"] = round(res["killed"] / res["total"], 3) if res["total"] else None
    return res
