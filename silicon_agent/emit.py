"""Deterministic SystemVerilog emitter for MatmulArch.

Design: output-stationary systolic array, PE[i][j] owns C[i][j].
A rows flow left->right (row i skewed by i cycles), B columns flow
top->bottom (column j skewed by j cycles). The host pushes one K-step
per cycle with `in_valid`; `in_last` marks the final K-step of a tile.
Each PE snapshots its accumulator into a shadow register when the last
step reaches it, so the next tile can start accumulating immediately.
Results drain row by row on `out_valid` while `busy` is high.

Latency-insensitive by construction: the testbench compares output
streams, never cycle positions, so pipeline knobs never break tests.
"""

from __future__ import annotations

from .ir import DSP_REG_MODES, MatmulArch


def drain_latency(a: MatmulArch) -> int:
    """Cycles after in_last before row 0 of C is valid on the output."""
    return (1 if a.reg_in else 0) + a.pe_cols + a.mul_latency


def min_k_full_rate(a: MatmulArch) -> int:
    """Smallest tile depth K for which back-to-back tiles never stall."""
    return drain_latency(a) + a.pe_rows + 1


def _dsp_instance(mode: str) -> str:
    """Explicit MULT18X18D with its internal registers configured by mode."""
    inr = "CLK0" if mode in ("in_out", "in_pipe_out") else "NONE"
    pipe = "CLK0" if mode == "in_pipe_out" else "NONE"
    outr = "CLK0" if mode in ("out", "in_out", "in_pipe_out") else "NONE"
    A = ",".join(f".A{i}(a_ext[{i}])" for i in range(18))
    B = ",".join(f".B{i}(b_ext[{i}])" for i in range(18))
    C = ",".join(f".C{i}(1'b0)" for i in range(18))
    P = ",".join(f".P{i}(p_full[{i}])" for i in range(36))
    return f"""    logic [17:0] a_ext, b_ext;
    logic [35:0] p_full;
    assign a_ext = {{{{18-W{{a_in[W-1]}}}}, a_in}};
    assign b_ext = {{{{18-W{{b_in[W-1]}}}}, b_in}};
    MULT18X18D #(
        .REG_INPUTA_CLK("{inr}"), .REG_INPUTB_CLK("{inr}"), .REG_PIPELINE_CLK("{pipe}"), .REG_OUTPUT_CLK("{outr}"),
        .REG_INPUTA_CE("CE0"), .REG_INPUTB_CE("CE0"), .REG_PIPELINE_CE("CE0"), .REG_OUTPUT_CE("CE0"),
        .REG_INPUTA_RST("RST0"), .REG_INPUTB_RST("RST0"), .REG_PIPELINE_RST("RST0"), .REG_OUTPUT_RST("RST0"),
        .GSR("DISABLED"), .RESETMODE("SYNC"), .CAS_MATCH_REG("FALSE"), .SOURCEB_MODE("B_SHIFT"), .MULT_BYPASS("DISABLED")
    ) u_mult (
        {A},
        {B},
        {C},
        .SIGNEDA(1'b1), .SIGNEDB(1'b1), .SOURCEA(1'b0), .SOURCEB(1'b0),
        .CLK0(clk), .CE0(1'b1), .RST0(1'b0),
        {P}
    );
    assign prod = p_full[2*W-1:0];
"""


def emit_matmul(a: MatmulArch) -> str:
    R, C, W, AW, P = a.pe_rows, a.pe_cols, a.data_width, a.acc_width, a.pipe_mul
    reg_in = 1 if a.reg_in else 0
    drain = drain_latency(a)
    dsp_lat = DSP_REG_MODES[a.dsp_regs]
    tok_row_shift = "{tok_row[R-2:0], tok_wait[DRAIN-1]}" if R > 1 else "tok_wait[DRAIN-1]"
    tok_wait_shift = "{tok_wait[DRAIN-2:0], in_valid & in_last}" if drain > 1 else "in_valid & in_last"
    mult = "    assign prod = a_in * b_in;\n" if a.dsp_regs == "none" else _dsp_instance(a.dsp_regs)
    return f"""// Generated by silicon-agent -- do not edit. IR: {a.to_dict()}
`default_nettype none

module pe #(
    parameter int W  = {W},
    parameter int AW = {AW},
    parameter int P  = {P},
    parameter int DL = {dsp_lat}
) (
    input  wire                  clk,
    input  wire                  rst,
    input  wire                  en,
    input  wire                  last,
    input  wire signed [W-1:0]   a_in,
    input  wire signed [W-1:0]   b_in,
    output logic signed [W-1:0]  a_out,
    output logic signed [W-1:0]  b_out,
    output logic signed [AW-1:0] acc_out
);
    logic signed [2*W-1:0] prod;
    logic signed [AW-1:0]  acc;
    logic signed [2*W-1:0] prod_s;   // product as seen by the accumulator
    logic                  en_s;
    logic                  last_s;

    // systolic pass-through
    always_ff @(posedge clk) begin
        a_out <= a_in;
        b_out <= b_in;
    end

{mult}
    // control must match the multiplier latency (DSP-internal regs + fabric pipe)
    generate
        if (DL + P == 0) begin : g_ctl0
            assign en_s   = en;
            assign last_s = last;
        end else begin : g_ctl
            logic [DL+P-1:0] en_d, last_d;
            always_ff @(posedge clk) begin
                en_d[0]   <= en;
                last_d[0] <= last;
                for (int s = 1; s < DL + P; s++) begin
                    en_d[s]   <= en_d[s-1];
                    last_d[s] <= last_d[s-1];
                end
            end
            assign en_s   = en_d[DL+P-1];
            assign last_s = last_d[DL+P-1];
        end
    endgenerate

    generate
        if (P == 0) begin : g_nopipe
            assign prod_s = prod;
        end else begin : g_pipe
            logic [P-1:0][2*W-1:0] prod_q;
            always_ff @(posedge clk) begin
                prod_q[0] <= prod;
                for (int s = 1; s < P; s++) prod_q[s] <= prod_q[s-1];
            end
            assign prod_s = $signed(prod_q[P-1]);
        end
    endgenerate

    always_ff @(posedge clk) begin
        if (rst) begin
            acc     <= '0;
            acc_out <= '0;
        end else if (en_s) begin
            if (last_s) begin
                acc_out <= acc + AW'(prod_s);
                acc     <= '0;
            end else begin
                acc <= acc + AW'(prod_s);
            end
        end
    end
endmodule


module matmul_top #(
    parameter int R  = {R},
    parameter int C  = {C},
    parameter int W  = {W},
    parameter int AW = {AW}
) (
    input  wire                     clk,
    input  wire                     rst,
    // one K-step per cycle: column k of A (R values) and row k of B (C values)
    input  wire                     in_valid,
    input  wire                     in_last,
    input  wire [R*W-1:0]           a_col,
    input  wire [C*W-1:0]           b_row,
    output logic                    busy,
    output logic                    out_valid,
    output logic [$clog2(R+1)-1:0]  out_row,
    output logic [C*AW-1:0]         c_row
);
    localparam int DRAIN = {drain};

    // ---- boundary register (optional) ----
    logic [R-1:0][W-1:0] a_bnd;
    logic [C-1:0][W-1:0] b_bnd;
    logic                v_bnd, l_bnd;

    generate
        if ({reg_in}) begin : g_reg_in
            always_ff @(posedge clk) begin
                a_bnd <= a_col;
                b_bnd <= b_row;
                v_bnd <= in_valid;
                l_bnd <= in_last;
            end
        end else begin : g_no_reg_in
            assign a_bnd = a_col;
            assign b_bnd = b_row;
            assign v_bnd = in_valid;
            assign l_bnd = in_last;
        end
    endgenerate

    // ---- input skew: row i of A delayed i cycles, column j of B delayed j ----
    logic [R-1:0][R-1:0][W-1:0] a_skew;
    logic [C-1:0][C-1:0][W-1:0] b_skew;
    logic [R+C-1:0]             v_skew, l_skew;

    always_ff @(posedge clk) begin
        v_skew[0] <= v_bnd & ~rst;
        l_skew[0] <= l_bnd;
        for (int d = 1; d < R + C; d++) begin
            v_skew[d] <= v_skew[d-1];
            l_skew[d] <= l_skew[d-1];
        end
    end

    genvar gi, gj, gd;
    generate
        for (gi = 0; gi < R; gi++) begin : g_askew
            always_ff @(posedge clk) a_skew[gi][0] <= a_bnd[gi];
            for (gd = 1; gd < R; gd++) begin : g_d
                always_ff @(posedge clk) a_skew[gi][gd] <= a_skew[gi][gd-1];
            end
        end
        for (gj = 0; gj < C; gj++) begin : g_bskew
            always_ff @(posedge clk) b_skew[gj][0] <= b_bnd[gj];
            for (gd = 1; gd < C; gd++) begin : g_d
                always_ff @(posedge clk) b_skew[gj][gd] <= b_skew[gj][gd-1];
            end
        end
    endgenerate

    // ---- PE array ----
    logic [R-1:0][C:0][W-1:0]    a_h;     // a_h[i][j] enters PE[i][j] from the left
    logic [R:0][C-1:0][W-1:0]    b_v;     // b_v[i][j] enters PE[i][j] from above
    logic [R-1:0][C-1:0][AW-1:0] acc_out;

    generate
        for (gi = 0; gi < R; gi++) begin : g_row
            assign a_h[gi][0] = a_skew[gi][gi];
            for (gj = 0; gj < C; gj++) begin : g_col
                if (gi == 0) begin : g_top
                    assign b_v[0][gj] = b_skew[gj][gj];
                end
                pe #(.W(W), .AW(AW), .P({P}), .DL({dsp_lat})) u_pe (
                    .clk    (clk),
                    .rst    (rst),
                    .en     (v_skew[gi+gj]),
                    .last   (l_skew[gi+gj]),
                    .a_in   (a_h[gi][gj]),
                    .b_in   (b_v[gi][gj]),
                    .a_out  (a_h[gi][gj+1]),
                    .b_out  (b_v[gi+1][gj]),
                    .acc_out(acc_out[gi][gj])
                );
            end
        end
    endgenerate

    // ---- drain: a token enters a shift chain on in_last; DRAIN cycles later it
    //      walks through R one-hot row slots, each slot emitting its C row. No
    //      counters or comparators: the token position IS the row select. ----
    logic [DRAIN-1:0] tok_wait;
    logic [R-1:0]     tok_row;     // one-hot: which row is being emitted this cycle
    logic [R-1:0]     tok_row_nxt;
    logic [C*AW-1:0]  c_sel;

    always_comb begin
        tok_row_nxt = {tok_row_shift};
        c_sel = '0;
        for (int i = 0; i < R; i++)
            c_sel |= acc_out[i] & {{(C*AW){{tok_row[i]}}}};
    end

    always_ff @(posedge clk) begin
        if (rst) begin
            tok_wait  <= '0;
            tok_row   <= '0;
            busy      <= 1'b0;
            out_valid <= 1'b0;
            out_row   <= '0;
            c_row     <= '0;
        end else begin
            tok_wait  <= {tok_wait_shift};
            tok_row   <= tok_row_nxt;
            out_valid <= |tok_row;
            c_row     <= c_sel;
            busy      <= (in_valid & in_last) | (|tok_wait) | (|tok_row_nxt);
            for (int i = 0; i < R; i++)
                if (tok_row[i]) out_row <= i[$clog2(R+1)-1:0];
        end
    end
endmodule

`default_nettype wire
"""
